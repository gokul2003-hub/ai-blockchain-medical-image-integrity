"""Phase 8 — REAL local IPFS node integration tests (GAP-05).

These tests contact a **real** IPFS Kubo daemon over its HTTP RPC API. Nothing
here is mocked: no `requests` patching, no fake daemon, no synthetic CIDs. Every
CID asserted by these tests was generated by the actual node from the actual
bytes, and content is genuinely retrieved and decrypted back to the original
image.

They are separated from the unit tests in ``test_ipfs_storage.py`` on purpose.

Running them
------------
Start a local Kubo node first (see docs/PHASE_6_IPFS_STORAGE.md), then:

    pytest backend/tests/test_ipfs_real_integration.py -q -c backend/pytest.ini

To force the configuration used by these tests:

    $env:STORAGE_PROVIDER = "ipfs"
    $env:IPFS_API_URL    = "http://127.0.0.1:5001"

If no daemon is reachable the whole module skips with a clear reason. A skipped
real-integration run is reported honestly rather than being counted as a pass.
"""

