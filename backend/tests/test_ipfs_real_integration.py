def _encrypted_fixture() -> tuple[bytes, bytes, str, str]:
    """Build a real preprocessed image and its AES-256-GCM ciphertext.

    Returns (preprocessed_png_bytes, encrypted_bytes, original_sha3, metadata).
    The metadata is the one produced *with* these ciphertext bytes, so it carries
    the matching nonce and AAD binding required to decrypt them.
    """
    import cv2

    from app.crypto import encrypt_image

    image = np.zeros((96, 96), dtype=np.uint8)
    cv2.ellipse(image, (48, 48), (26, 34), 25, 0, 360, 190, -1)
    cv2.circle(image, (38, 40), 11, 240, -1)
    ok, encoded = cv2.imencode(".png", image)
    assert ok
    preprocessed = encoded.tobytes()

    encrypted, original_hash, metadata = encrypt_image(preprocessed, 6.5)
    return preprocessed, encrypted, original_hash, metadata


