class TestNoSilentFallback:

    def test_production_refuses_to_start_without_ipfs(self):
        """15. APP_ENV=production + STORAGE_PROVIDER=ipfs + no daemon => boot fails."""
        import base64
        import dataclasses
        from unittest.mock import patch

        from app.config import load_settings

        environ = dict(os.environ)
        try:
            os.environ.update({
                "APP_ENV": "production",
                "STORAGE_PROVIDER": "ipfs",
                "IPFS_API_URL": "http://127.0.0.1:59999",
                "JWT_SECRET": "Kx9#mQ2$vL8@pR4wZc6!Jm3Xt9Qb2Lf7Vh5Nk8Sd1Ga4We6Y",
                "JWT_REFRESH_SECRET": "Rt4$wB8!Xq2Zm9Vk3Lp6Jh1Ns5Dc7Fg0Ay2Eu4Io8Uz6Ta",
                "MASTER_KEY": base64.urlsafe_b64encode(b"\x07" * 32).decode(),
                "ALLOWED_ORIGINS": "https://med.example.com",
                "MFA_TEST_MODE": "false",
            })
            production = load_settings()

            # The production + ipfs combination is exactly what the startup guard keys on.
            assert production.is_production is True
            assert production.storage_provider == "ipfs"

            with patch("app.storage_provider.settings", production):
                with pytest.raises(RuntimeError, match="not an automatic fallback"):
                    assert_ipfs_available()
        finally:
            os.environ.clear()
            os.environ.update(environ)

    def test_startup_guard_condition_is_met_only_for_production_ipfs(self):
        """The guard must not fire in dev, and not for an explicit local provider."""
        import base64
        import dataclasses

        from app.config import load_settings

        environ = dict(os.environ)
        try:
            os.environ.update({
                "STORAGE_PROVIDER": "local",
                "IPFS_API_URL": "http://127.0.0.1:59999",
            })
            local_dev = load_settings()
            # Unreachable IPFS is irrelevant when the provider is local.
            assert not (local_dev.is_production and local_dev.storage_provider == "ipfs")
            assert_ipfs_available()  # live node still reachable via the real URL

            os.environ.update({
                "APP_ENV": "production",
                "STORAGE_PROVIDER": "local",
                "JWT_SECRET": "Kx9#mQ2$vL8@pR4wZc6!Jm3Xt9Qb2Lf7Vh5Nk8Sd1Ga4We6Y",
                "JWT_REFRESH_SECRET": "Rt4$wB8!Xq2Zm9Vk3Lp6Jh1Ns5Dc7Fg0Ay2Eu4Io8Uz6Ta",
                "MASTER_KEY": base64.urlsafe_b64encode(b"\x07" * 32).decode(),
                "ALLOWED_ORIGINS": "https://med.example.com",
                "MFA_TEST_MODE": "false",
            })
            local_prod = load_settings()
            assert local_prod.is_production is True
            assert local_prod.storage_provider == "local"
            assert not (local_prod.is_production and local_prod.storage_provider == "ipfs")
        finally:
            os.environ.clear()
            os.environ.update(environ)

    def test_production_still_requires_ipfs_when_node_is_up(self):
        """With a live node the same production configuration passes the guard."""
        assert_ipfs_available()

    def test_store_encrypted_object_does_not_downgrade_provider(self):
        """An explicit ipfs request must never be served by the local provider."""
        from app.storage_provider import get_storage_provider, store_encrypted_object

        assert get_storage_provider("ipfs").name == "ipfs"
        stored = store_encrypted_object(
            b"PHASE4_NO_DOWNGRADE_PROBE", "nodowngrade.enc", provider_name="ipfs"
        )
        try:
            assert stored.provider == "ipfs"
            assert stored.reference.startswith(("Qm", "baf"))
        finally:
            IPFSProvider().delete(stored.reference)

    def test_unsupported_provider_name_is_rejected(self):
        from app.storage_provider import get_storage_provider

        with pytest.raises(ValueError, match="Unsupported storage provider"):
            get_storage_provider("s3")