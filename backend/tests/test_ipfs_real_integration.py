class TestEncryptedOnlyStorage:

    def test_ipfs_never_receives_the_plaintext_image(self):
        """9, 15. Stored bytes differ from the source image and decrypt back to it.

        This is the core confidentiality assertion: what lands on IPFS is
        ciphertext, not the medical image.
        """
        preprocessed, encrypted, original_hash, metadata = _encrypted_fixture()
        provider = IPFSProvider()
        stored = provider.put(encrypted, "confidentiality.enc")

        try:
            from_ipfs = provider.get(stored.reference)

            # 1. The stored object is NOT the plaintext image.
            assert from_ipfs != preprocessed
            assert from_ipfs[:8] != preprocessed[:8]
            assert preprocessed not in from_ipfs

            # 2. It IS exactly the application's encrypted payload.
            assert from_ipfs == encrypted

            # 3. And it decrypts back to the original through the real pipeline,
            #    using the metadata that was produced alongside these bytes.
            from app.crypto import decrypt_image, sha3_hash

            recovered = decrypt_image(from_ipfs, original_hash, metadata)
            assert recovered == preprocessed
            assert sha3_hash(recovered) == original_hash
        finally:
            provider.delete(stored.reference)

    def test_encrypted_payload_is_unreadable_as_an_image(self):
        """Ciphertext must not decode as a PNG; no accidental plaintext leak."""
        import cv2

        _, encrypted, _, _ = _encrypted_fixture()
        provider = IPFSProvider()
        stored = provider.put(encrypted, "not_an_image.enc")
        try:
            retrieved = provider.get(stored.reference)
            assert not cv2.imdecode(
                np.frombuffer(retrieved, dtype=np.uint8), cv2.IMREAD_UNCHANGED
            ), "stored object must not be a decodable image"
        finally:
            provider.delete(stored.reference)

    def test_full_lifecycle_through_the_storage_abstraction(self):
        """16. store -> twin reference -> load -> decrypt == original bytes.

        Uses the application's own store/load helpers, so this exercises the same
        path the upload and download routes use.
        """
        from app.crypto import decrypt_image
        from app.storage_provider import load_encrypted_object, store_encrypted_object

        preprocessed, encrypted, _, _ = _encrypted_fixture()
        # Store the ciphertext the upload route would have produced.
        stored = store_encrypted_object(encrypted, "lifecycle.enc", provider_name="ipfs")
        assert stored.provider == "ipfs"

        try:
            assert verify_ipfs_pin(stored.reference) is True
            loaded = load_encrypted_object(stored.reference)
            assert loaded == encrypted
            assert verify_stored_content(stored.reference, stored.sha256, "ipfs") is True
        finally:
            IPFSProvider().delete(stored.reference)


