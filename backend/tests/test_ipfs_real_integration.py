class TestRealUploadAndRetrieval:

    def test_encrypted_payload_uploads_and_returns_real_cid(self):
        """3-4. A real CID is generated by the node for the encrypted payload."""
        _, encrypted, _, _ = _encrypted_fixture()
        stored = IPFSProvider().put(encrypted, f"real_{uuid.uuid4().hex[:8]}.enc")

        try:
            assert stored.provider == "ipfs"
            assert stored.size == len(encrypted)
            # The CID is well-formed and came from the daemon, not from us.
            assert validate_ipfs_cid(stored.reference) == stored.reference
            assert stored.reference.startswith(("Qm", "bafy", "bafk", "bag"))
            assert len(stored.reference) >= 46
        finally:
            IPFSProvider().delete(stored.reference)

    def test_cid_is_content_addressed_and_deterministic(self):
        """5. The same bytes always yield the same CID; different bytes do not."""
        payload_a = b"PHASE4_CONTENT_ADDRESSING_PROBE_A"
        payload_b = b"PHASE4_CONTENT_ADDRESSING_PROBE_B"
        provider = IPFSProvider()

        first = provider.put(payload_a, "probe_a.enc")
        second = provider.put(payload_a, "probe_a.enc")
        other = provider.put(payload_b, "probe_b.enc")

        try:
            assert first.reference == second.reference, "CID must be deterministic for identical bytes"
            assert first.reference != other.reference, "different bytes must yield different CIDs"
        finally:
            provider.delete(first.reference)
            provider.delete(other.reference)

    def test_retrieved_bytes_match_stored_encrypted_payload(self):
        """7-8. What comes back is byte-identical to what was stored."""
        _, encrypted, _, _ = _encrypted_fixture()
        provider = IPFSProvider()
        stored = provider.put(encrypted, "roundtrip.enc")

        try:
            retrieved = provider.get(stored.reference)
            assert retrieved == encrypted
            assert len(retrieved) == stored.size
            assert stored.sha256 == __import__("hashlib").sha256(retrieved).hexdigest()
        finally:
            provider.delete(stored.reference)

    def test_stored_content_verification_passes_and_detects_mismatch(self):
        """11. verify_stored_content() confirms fidelity and rejects a bad digest."""
        _, encrypted, _, _ = _encrypted_fixture()
        provider = IPFSProvider()
        stored = provider.put(encrypted, "verify.enc")

        try:
            assert verify_stored_content(stored.reference, stored.sha256, "ipfs") is True
            assert verify_stored_content(stored.reference, "0" * 64, "ipfs") is False
        finally:
            provider.delete(stored.reference)

    def test_cid_is_pinned_after_upload(self):
        """6. Upload pins the CID; unpinning is observable."""
        payload = b"PHASE4_PIN_PROBE_PAYLOAD"
        provider = IPFSProvider()
        stored = provider.put(payload, "pin.enc")

        try:
            assert verify_ipfs_pin(stored.reference) is True
        finally:
            provider.delete(stored.reference)

        assert verify_ipfs_pin(stored.reference) is False, "delete() must actually unpin"

    def test_large_payload_round_trips(self):
        """A realistically sized encrypted payload survives the round trip."""
        rng = np.random.default_rng(20261004)
        payload = rng.integers(0, 256, size=400_000, dtype=np.uint8).tobytes()
        provider = IPFSProvider()
        stored = provider.put(payload, "large.enc")
        try:
            assert stored.size == len(payload)
            assert provider.get(stored.reference) == payload
        finally:
            provider.delete(stored.reference)


