class TestRealFailureHandling:

    def test_invalid_cid_is_rejected_before_any_network_call(self):
        """12. Malformed CIDs never reach the daemon."""
        for bad in ["../../etc/passwd", "not a cid", "Qm1", "bafkrei/../x", ""]:
            with pytest.raises(ValueError):
                IPFSProvider().get(bad)

    def test_unknown_but_wellformed_cid_fails_retrieval(self):
        """8. A syntactically valid CID that the node does not hold fails loudly."""
        # Well-formed CIDv1 that has never been added to this node.
        missing = "bafkreigdfr3wqvw5v3v5b2xtbmt5g2rtv3azq7hvwvzbmnpb5zkbnhtwqvy"
        with pytest.raises(RuntimeError):
            IPFSProvider().get(missing)

    def test_unreachable_daemon_raises_rather_than_falling_back(self):
        """13-14. With IPFS down, uploads fail loudly and never touch local disk."""
        import dataclasses
        from unittest.mock import patch

        from app.storage_provider import LocalStorageProvider

        # Settings is a frozen dataclass, so a closed port is injected by
        # swapping in a modified copy rather than mutating the live instance.
        down = dataclasses.replace(settings, ipfs_api_url="http://127.0.0.1:59999")

        with patch("app.storage_provider.settings", down):
            assert ipfs_is_reachable() is False

            with pytest.raises(RuntimeError, match="IPFS upload failed"):
                IPFSProvider().put(b"PHASE4_UNREACHABLE_PROBE", "nope.enc")

            with pytest.raises(RuntimeError, match="(?i)refusing to start"):
                assert_ipfs_available()

            # Nothing was written to the local encrypted directory by a failed upload.
            from app.config import ENCRYPTED_DIR

            def snapshot():
                return set(p.name for p in ENCRYPTED_DIR.glob("*")) if ENCRYPTED_DIR.exists() else set()

            before = snapshot()
            with pytest.raises(RuntimeError):
                IPFSProvider().put(b"PHASE4_UNREACHABLE_PROBE_2", "nope2.enc")
            assert before == snapshot(), "a failed IPFS upload must not create local storage"

        # The local provider still works when it is explicitly selected.
        local = LocalStorageProvider()
        local_ref = local.put(b"PHASE4_LOCAL_CONTROL", "control.enc")
        try:
            assert local.get(local_ref.reference) == b"PHASE4_LOCAL_CONTROL"
        finally:
            local.delete(local_ref.reference)

    def test_empty_payload_is_refused(self):
        with pytest.raises(ValueError):
            IPFSProvider().put(b"", "empty.enc")

    def test_pin_verification_is_false_not_raising_when_daemon_down(self):
        """A downed daemon yields False, never an exception, for display paths."""
        import dataclasses
        from unittest.mock import patch

        down = dataclasses.replace(settings, ipfs_api_url="http://127.0.0.1:59999")
        with patch("app.storage_provider.settings", down):
            assert verify_ipfs_pin("bafkreigdfr3wqvw5v3v5b2xtbmt5g2rtv3azq7hvwvzbmnpb5zkbnhtwqvy") is False


